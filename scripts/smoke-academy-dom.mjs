import assert from 'node:assert/strict';
import fs from 'node:fs';
import { JSDOM } from 'jsdom';
const dom = new JSDOM(fs.readFileSync(new URL('../public/academy.html', import.meta.url), 'utf8'), { url: 'https://example.test/academy?role=admin', runScripts: 'outside-only' });
const w = dom.window, d = w.document;
w.confirm = () => true;
w.eval(fs.readFileSync(new URL('../public/assets/js/academy.js', import.meta.url), 'utf8'));
w.MizanoraAcademy.mountAll();
const $ = selector => d.querySelector(selector);
const change = el => el.dispatchEvent(new w.Event('change', { bubbles: true }));
let count = 0;
const check = (name, condition) => { assert.ok(condition, name); count++; console.log('  ✓ ' + name); };
check('Academy supplies 17 practical lessons', w.MizanoraAcademy.lessons.length === 17);
check('Admin track filters to six lessons', d.querySelectorAll('[data-lesson]').length === 6);
$('[data-lesson="a1"]').click();
$('[data-complete]').click();
check('Completion requires evidence and knowledge check', $('[data-complete-result]').textContent.includes('Complete all steps'));
$('input[name="quiz-a1"][value="0"]').checked = true;
$('[data-quiz-check]').click();
check('Incorrect answer does not pass', $('[data-quiz-result]').textContent.includes('Not quite'));
$('input[name="quiz-a1"][value="1"]').checked = true;
$('[data-quiz-check]').click();
d.querySelectorAll('[data-step], [data-practical]').forEach(el => { el.checked = true; change(el); });
$('[data-complete]').click();
check('Completed practical lesson persists locally', JSON.parse(w.localStorage.getItem('mz_academy_v6')).a1.done === true);
check('Progress count updates', $('.academy-progress').textContent.startsWith('1/6'));
const search = $('[data-academy-search]'); search.value = 'no-such-lesson'; search.dispatchEvent(new w.Event('input', { bubbles: true }));
check('Search empty state is useful', $('.academy-lessons').textContent.includes('No matching lessons'));
search.value = ''; search.dispatchEvent(new w.Event('input', { bubbles: true }));
const role = $('[data-academy-role]'); role.value = 'setup'; change(role);
check('Setup track contains five lessons', d.querySelectorAll('[data-lesson]').length === 5);
$('[data-academy-reset]').click();
check('Progress reset clears saved completion', !JSON.parse(w.localStorage.getItem('mz_academy_v6')).a1);
const before = d.querySelectorAll('.academy').length; w.MizanoraAcademy.mountAll();
check('Remount does not duplicate lesson widgets', before === d.querySelectorAll('.academy').length);
dom.window.close();
console.log(`${count}/${count} Academy DOM checks passed`);
